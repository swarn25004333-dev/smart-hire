function buildCandidate(seed: CandidateSeed, index: number, blind: boolean): CandidateAnalysis {
  const base: CandidateAnalysis = {
    candidateId: `c${index + 1}`,
    name: seed.name,
    email: seed.email,
    phone: seed.phone,
    address: seed.city,
    overallScore: seed.overallScore,
    matchCategory: seed.matchCategory,
    scoreBreakdown: {
      requiredSkills: Math.min(100, Math.round(seed.machineLearning * 0.4 + seed.backend * 0.3 + seed.frontend * 0.1 + seed.cloud * 0.2)),
      experience: Math.min(100, Math.round(seed.experience / 10 * 100)),
      projects: Math.min(100, Math.round(seed.problemSolving * 0.4 + seed.machineLearning * 0.3 + seed.backend * 0.3)),
      education: 85,
      certifications: seed.certifications.length > 0 ? 90 : 60,
      preferredSkills: Math.min(100, Math.round(seed.problemSolving * 0.3 + seed.machineLearning * 0.4 + seed.backend * 0.3)),
    },
    skillsMatch: seed.topSkills.slice(0, 6),
    missingSkills: seed.missingSkills,
    strengths: seed.strengths,
    weaknesses: seed.weaknesses,
    whyMatches: seed.whyMatches,
    skillGaps: seed.skillGaps,
    recommendation: seed.recommendation,
    recommendationExplanation: seed.recommendationExplanation,
    experienceYears: seed.experience,
    educationLevel: `${seed.degree}, ${seed.university}`,
    topSkills: seed.topSkills,
    certifications: seed.certifications,
    evidence: seed.resumeSummary,
  }

  if (blind) {
    base.name = `Candidate ${index + 1}`
    base.email = 'Hidden'
    base.phone = 'Hidden'
    base.address = undefined
  }

  return base
}

export function generateMockResult(blind: boolean): ScreeningResult {
  const candidates = seeds.map((seed, i) => buildCandidate(seed, i, blind))
  const avg = candidates.reduce((sum, c) => sum + c.overallScore, 0) / candidates.length

  return {
    jobId: `mock-${Date.now()}`,
    jobTitle: mockJobAnalysis.title,
    analyzedAt: new Date().toISOString(),
    totalCandidates: candidates.length,
    strongMatches: candidates.filter((c) => c.matchCategory === 'strong').length,
    averageScore: Math.round(avg),
    shortlisted: candidates.filter((c) => c.overallScore >= 75).length,
    jobAnalysis: mockJobAnalysis,
    candidates: candidates.sort((a, b) => b.overallScore - a.overallScore),
    engine: 'offline',
    poweredBy: 'Offline AI Mode',
    autoCompare: undefined,
  }
}

